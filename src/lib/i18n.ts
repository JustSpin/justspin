export const LOCALES = [
  { id: "en", native: "English", english: "English", html: "en" },
  { id: "es", native: "Español", english: "Spanish", html: "es" },
  { id: "pt", native: "Português", english: "Portuguese", html: "pt" },
  { id: "fr", native: "Français", english: "French", html: "fr" },
  { id: "de", native: "Deutsch", english: "German", html: "de" },
  { id: "zh", native: "中文", english: "Chinese", html: "zh-CN" },
  { id: "ko", native: "한국어", english: "Korean", html: "ko" },
] as const;

export type Locale = (typeof LOCALES)[number]["id"];

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && LOCALES.some((l) => l.id === v);
}

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const list = [navigator.language, ...(navigator.languages ?? [])];
  for (const raw of list) {
    const low = raw.toLowerCase();
    if (low.startsWith("zh")) return "zh";
    if (low.startsWith("pt")) return "pt";
    const short = low.slice(0, 2) as Locale;
    if (isLocale(short)) return short;
  }
  return "en";
}

export function htmlLang(locale: Locale): string {
  return LOCALES.find((l) => l.id === locale)?.html ?? "en";
}

function fill(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function t(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const dict = MESSAGES[locale] ?? MESSAGES.en;
  return fill(dict[key] ?? MESSAGES.en[key] ?? key, vars);
}

export function cuisineName(locale: Locale, id: string, fallback: string) {
  return CUISINE[locale]?.[id]?.label ?? CUISINE.en[id]?.label ?? fallback;
}

export function cuisineKicker(locale: Locale, id: string, fallback: string) {
  return CUISINE[locale]?.[id]?.kicker ?? CUISINE.en[id]?.kicker ?? fallback;
}

